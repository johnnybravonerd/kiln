"""Kiln -> C code generator (consumes the type-annotated AST)."""

from __future__ import annotations
from . import ast_nodes as A
from .ktypes import (Arr, StructT, INT, FLOAT, BOOL, STR, UNIT, NEVER, PTR, CSTR,
                    SIZED_INTS, SIZED_C, prune, mangle)
from .runtime import RUNTIME_C
from .checker import Checker
from . import __version__


def c_string(s: str) -> tuple[str, int]:
    data = s.encode("utf-8")
    out = []
    for b in data:
        c = chr(b)
        if c == '"':
            out.append('\\"')
        elif c == "\\":
            out.append("\\\\")
        elif c == "?":
            out.append("\\?")
        elif 32 <= b < 127:
            out.append(c)
        elif c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append("\\t")
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"', len(data)


def c_int(v: int) -> str:
    """64-bit integer constant (bare C literals are 32-bit `int`)."""
    if v == -2**63:
        return "INT64_MIN"
    return f"INT64_C({v})" if v >= 0 else f"(-INT64_C({-v}))"


def c_float(v: float) -> str:
    r = repr(float(v))
    if "e" not in r and "." not in r:
        r += ".0"
    return r if v >= 0 else f"({r})"


class CGen:
    def __init__(self, checker: Checker, filename: str):
        self.ck = checker
        self.file = filename
        self.lines: list[str] = []
        self.ind = 1
        self.tmp = 0

    # ── utilities ──────────────────────────────────────────────────
    def emit(self, s: str):
        self.lines.append("    " * self.ind + s)

    def new_tmp(self, prefix="_t") -> str:
        self.tmp += 1
        return f"{prefix}{self.tmp}"

    def ctype(self, t) -> str:
        t = prune(t)
        if t is INT:
            return "int64_t"
        if t is FLOAT:
            return "double"
        if t is BOOL:
            return "bool"
        if t is STR:
            return "kstr"
        if t is PTR:
            return "void *"
        if t is CSTR:
            return "const char *"
        if t in SIZED_INTS:
            return SIZED_C[t]
        if t is UNIT or t is NEVER:
            return "void"
        if isinstance(t, Arr):
            return "karr_" + mangle(t.elem) + " *"
        if isinstance(t, StructT):
            return "S_" + t.name
        raise ValueError(f"no C type for {t!r}")

    def arrname(self, t) -> str:
        t = prune(t)
        return "karr_" + mangle(t.elem)

    def to_str(self, t, c: str, repr_mode=False) -> str:
        t = prune(t)
        if t is INT or t in SIZED_INTS:
            return f"k_str_int((int64_t)({c}))"
        if t is FLOAT:
            return f"k_str_float({c})"
        if t is BOOL:
            return f"k_str_bool({c})"
        if t is PTR:
            return f"k_str_ptr({c})"
        if t is CSTR:
            return f"k_str_cstr({c})"
        if t is STR:
            return f"k_repr_str({c})" if repr_mode else c
        if isinstance(t, Arr):
            return f"{self.arrname(t)}_repr({c})"
        if isinstance(t, StructT):
            return f"S_{t.name}_repr({c})"
        raise ValueError(f"cannot stringify {t!r}")

    def capture(self, fn):
        """Run fn() collecting emitted lines separately; returns (lines, result)."""
        saved = self.lines
        self.lines = []
        try:
            r = fn()
            return self.lines, r
        finally:
            self.lines = saved

    def loc_str(self, node) -> str:
        loc = node.loc
        return c_string(f"{loc.file}:{loc.line}:{loc.col}")[0] if loc else '"?"'

    # ── program ────────────────────────────────────────────────────
    def gen_program(self, prog: A.Program, test_mode: bool = False) -> str:
        ck = self.ck
        out: list[str] = [f"/* Generated by the Kiln compiler {__version__} from {self.file}. Do not edit. */",
                          RUNTIME_C]
        arrs = ck.concrete_types()
        structs = list(ck.structs.values())
        # forward declarations
        for st in structs:
            out.append(f"typedef struct S_{st.name} S_{st.name};")
        for k, t in arrs.items():
            if k != "arr_str":
                out.append(f"typedef struct karr_{k[4:]} karr_{k[4:]};")
        for k, t in arrs.items():
            if k != "arr_str":
                out.append(f"KARR_STRUCT(karr_{k[4:]}, {self.ctype(t.elem)})")
        # struct definitions in dependency order
        done = set()

        def emit_struct(st):
            if st.name in done:
                return
            done.add(st.name)
            for _, ft in st.fields:
                if isinstance(prune(ft), StructT):
                    emit_struct(prune(ft))
            out.append(f"struct S_{st.name} {{")
            for fname, ft in st.fields:
                out.append(f"    {self.ctype(ft)} {fname};")
            if not st.fields:
                out.append("    char _empty;")
            out.append("};")
        for st in structs:
            emit_struct(st)
        for k, t in arrs.items():
            if k != "arr_str":
                out.append(f"KARR_FUNCS(karr_{k[4:]}, {self.ctype(t.elem)})")
        # repr prototypes
        for k, t in arrs.items():
            out.append(f"static kstr karr_{k[4:]}_repr(karr_{k[4:]} *a);")
        for st in structs:
            out.append(f"static kstr S_{st.name}_repr(S_{st.name} v);")
        for k, t in arrs.items():
            n = f"karr_{k[4:]}"
            out.append(f"static kstr {n}_repr({n} *a) {{\n    k_sb b; k_sb_init(&b); k_sb_addc(&b, '[');\n"
                       f"    for (int64_t i = 0; i < a->len; i++) {{ if (i) k_sb_addn(&b, \", \", 2); "
                       f"k_sb_add(&b, {self.to_str(t.elem, 'a->data[i]', True)}); }}\n"
                       f"    k_sb_addc(&b, ']'); return k_sb_done(&b);\n}}")
            el = prune(t.elem)
            if el in (INT, FLOAT, BOOL, STR):
                eq = "k_str_eq(a->data[i], v)" if el is STR else "a->data[i] == v"
                out.append(f"static bool {n}_contains({n} *a, {self.ctype(el)} v) {{\n"
                           f"    for (int64_t i = 0; i < a->len; i++) if ({eq}) return true;\n    return false;\n}}")
            if el in (INT, FLOAT, STR):
                cmp = {INT: "k_cmp_int", FLOAT: "k_cmp_float", STR: "k_cmp_str"}[el]
                out.append(f"static {n} *{n}_sorted({n} *a) {{\n    {n} *r = {n}_slice(a, 0, a->len);\n"
                           f"    qsort(r->data, (size_t)r->len, sizeof(r->data[0]), {cmp});\n    return r;\n}}")
            if el in (INT, FLOAT):
                out.append(f"static {self.ctype(el)} {n}_sum({n} *a) {{\n    {self.ctype(el)} s = 0;\n"
                           f"    for (int64_t i = 0; i < a->len; i++) s += a->data[i];\n    return s;\n}}")
        for st in structs:
            parts = [f"static kstr S_{st.name}_repr(S_{st.name} v) {{",
                     "    k_sb b; k_sb_init(&b);",
                     f"    k_sb_addn(&b, {c_string(st.name + ' {')[0]}, {len(st.name) + 2});"]
            for i, (fname, ft) in enumerate(st.fields):
                lit, ln = c_string((", " if i else " ") + fname + ": ")
                parts.append(f"    k_sb_addn(&b, {lit}, {ln});")
                parts.append(f"    k_sb_add(&b, {self.to_str(ft, 'v.' + fname, True)});")
            parts.append('    k_sb_addn(&b, " }", 2);' if st.fields else "")
            parts.append("    return k_sb_done(&b);\n}")
            out.append("\n".join(parts))
        # globals
        for g in ck.global_inits:
            out.append(f"static {self.ctype(g.sym.ty)} {g.sym.cname};")
        # extern FFI declarations (non-static, linked from system / kiln_gfx)
        seen_ext = set()
        for info in ck.extern_fns:
            if info.cname in seen_ext:
                continue
            seen_ext.add(info.cname)
            out.append(self.extern_header(info) + ";")
        # prototypes for Kiln functions
        fns = [d for d in prog.decls if isinstance(d, A.FnDecl) and not d.is_extern]
        for d in fns:
            out.append(self.fn_header(d.info) + ";")
        # global initializer
        self.lines = []
        self.ind = 1
        for g in ck.global_inits:
            c = self.gen_expr(g.value)
            self.emit(f"{g.sym.cname} = {c};")
        out.append("static void k_init_globals(void) {")
        out.extend(self.lines)
        out.append("}")
        # functions
        for d in fns:
            out.append(self.gen_fn(d))
        # tests
        if test_mode:
            tests = [d for d in prog.decls if isinstance(d, A.TestDecl)]
            for i, t in enumerate(tests):
                self.lines = []
                self.ind = 1
                self.tmp = 0
                self.gen_block_stmts(t.body, None)
                out.append(f"static void k_test_{i}(void) {{")
                out.extend(self.lines)
                out.append("}")
            out.append("int main(int argc, char **argv) {\n    k_init(argc, argv);\n"
                       "    k_init_globals();\n    int failed = 0, passed = 0;\n    jmp_buf jb;")
            for i, t in enumerate(tests):
                lit, _ = c_string(t.name)
                out.append(f"    printf(\"test \\\"%s\\\" ... \", {lit}); fflush(stdout);\n"
                           f"    k_test_jmp = &jb;\n"
                           f"    if (setjmp(jb) == 0) {{ k_test_{i}(); k_test_jmp = NULL; printf(\"ok\\n\"); passed++; }}\n"
                           f"    else {{ k_test_jmp = NULL; printf(\"FAILED\\n    %s\\n\", k_test_msg); failed++; }}")
            out.append("    printf(\"\\n%d passed, %d failed\\n\", passed, failed);\n    return failed ? 1 : 0;\n}")
        else:
            m = ck.fns["main"]
            call_args = "k_make_args()" if m.params else ""
            body = [f"int main(int argc, char **argv) {{", "    k_init(argc, argv);",
                    "    k_init_globals();"]
            if prune(m.ret) is INT:
                body.append(f"    int64_t rc = f_main({call_args});\n    fflush(stdout);\n    return (int)rc;")
            else:
                body.append(f"    f_main({call_args});\n    fflush(stdout);\n    return 0;")
            body.append("}")
            out.append("\n".join(body))
        return "\n".join(out) + "\n"

    def fn_header(self, info) -> str:
        if getattr(info.decl, "param_syms", None):
            ps = ", ".join(f"{self.ctype(t)} {sym.cname}" for (_, t), sym in zip(info.params, info.decl.param_syms)) or "void"
        else:
            ps = ", ".join(f"{self.ctype(t)}" for _, t in info.params) or "void"
        ret = self.ctype(info.ret)
        return f"static {ret} {info.cname}({ps})"

    def extern_header(self, info) -> str:
        ps = ", ".join(f"{self.ctype(t)}" for _, t in info.params) or "void"
        ret = self.ctype(info.ret)
        if ret == "void":
            return f"{ret} {info.cname}({ps})"
        return f"{ret} {info.cname}({ps})"

    def gen_fn(self, d: A.FnDecl) -> str:
        info = d.info
        self.lines = []
        self.ind = 1
        self.tmp = 0
        want = prune(info.ret) is not UNIT
        self.gen_block_stmts(d.body, ("return",) if want else None)
        body = "\n".join(self.lines)
        return f"{self.fn_header(info)} {{\n{body}\n}}"

    # ── blocks & statements ────────────────────────────────────────
    def gen_block_stmts(self, b: A.Block, mode):
        """Emit statements of a block. mode: None | ("assign", cname) | ("return",)"""
        n = len(b.stmts)
        for i, s in enumerate(b.stmts):
            last = i == n - 1
            if last and mode is not None and isinstance(s, A.ExprStmt):
                self.gen_value_into(s.expr, mode)
            else:
                self.gen_stmt(s)

    def gen_value_into(self, e, mode):
        t = prune(e.ty)
        if t is NEVER or t is UNIT:
            c = self.gen_expr(e)
            if c:
                self.emit(c + ";")
            if mode[0] == "return" and t is UNIT:
                self.emit("return;")
            return
        if isinstance(e, A.IfExpr):
            self.gen_if(e, mode)
            return
        if isinstance(e, A.MatchExpr):
            self.gen_match(e, mode)
            return
        if isinstance(e, A.Block):
            self.emit("{")
            self.ind += 1
            self.gen_block_stmts(e, mode)
            self.ind -= 1
            self.emit("}")
            return
        c = self.gen_expr(e)
        if mode[0] == "return":
            self.emit(f"return {c};")
        else:
            self.emit(f"{mode[1]} = {c};")

    def gen_stmt(self, s):
        if isinstance(s, A.ExprStmt):
            c = self.gen_expr(s.expr)
            if c:
                self.emit(c + ";")
        elif isinstance(s, A.LetStmt):
            v = s.value
            if isinstance(v, (A.IfExpr, A.MatchExpr, A.Block)):
                self.emit(f"{self.ctype(s.sym.ty)} {s.sym.cname};")
                self.gen_value_into(v, ("assign", s.sym.cname))
            else:
                c = self.gen_expr(v)
                self.emit(f"{self.ctype(s.sym.ty)} {s.sym.cname} = {c};")
        elif isinstance(s, A.ReturnStmt):
            if s.value is None or prune(s.value.ty) is UNIT:
                if s.value is not None:
                    c = self.gen_expr(s.value)
                    if c:
                        self.emit(c + ";")
                self.emit("return;")
            else:
                self.gen_value_into(s.value, ("return",))
        elif isinstance(s, A.WhileStmt):
            pre, c = self.capture(lambda: self.gen_expr(s.cond))
            if pre:
                self.emit("for (;;) {")
                self.ind += 1
                self.lines.extend("    " * 0 + l for l in pre)
                self.emit(f"if (!({c})) break;")
            else:
                self.emit(f"while ({c}) {{")
                self.ind += 1
            self.gen_block_stmts(s.body, None)
            self.ind -= 1
            self.emit("}")
        elif isinstance(s, A.LoopStmt):
            self.emit("for (;;) {")
            self.ind += 1
            self.gen_block_stmts(s.body, None)
            self.ind -= 1
            self.emit("}")
        elif isinstance(s, A.ForStmt):
            self.gen_for(s)
        elif isinstance(s, A.BreakStmt):
            self.emit("break;")
        elif isinstance(s, A.ContinueStmt):
            self.emit("continue;")
        elif isinstance(s, A.GuardStmt):
            c = self.gen_expr(s.cond)
            self.emit(f"if (!({c})) {{")
            self.ind += 1
            self.gen_block_stmts(s.else_body, None)
            self.ind -= 1
            self.emit("}")
        elif isinstance(s, A.AssertStmt):
            c = self.gen_expr(s.cond)
            if s.msg is not None:
                m = self.gen_expr(s.msg)
            else:
                m = "KS(\"assert\", 6)"
            self.emit(f"k_assert({c}, {m}, {self.loc_str(s)});")
        else:
            raise NotImplementedError(type(s).__name__)

    def gen_for(self, s: A.ForStmt):
        v = s.sym.cname
        self.emit("{")
        self.ind += 1
        if s.kind == "range":
            a = self.gen_expr(s.iter.start)
            b = self.gen_expr(s.iter.end)
            end = self.new_tmp("_end")
            self.emit(f"int64_t {end} = {b};")
            op = "<=" if s.iter.inclusive else "<"
            self.emit(f"for (int64_t {v} = {a}; {v} {op} {end}; {v}++) {{")
        elif s.kind == "array":
            arr = self.new_tmp("_arr")
            k = self.new_tmp("_k")
            self.emit(f"{self.ctype(s.iter.ty)} {arr} = {self.gen_expr(s.iter)};")
            self.emit(f"for (int64_t {k} = 0; {k} < {arr}->len; {k}++) {{")
            self.emit(f"    {self.ctype(s.sym.ty)} {v} = {arr}->data[{k}];")
        else:  # str
            st = self.new_tmp("_s")
            k = self.new_tmp("_k")
            self.emit(f"kstr {st} = {self.gen_expr(s.iter)};")
            self.emit(f"for (int64_t {k} = 0; {k} < {st}.n; {k}++) {{")
            self.emit(f"    kstr {v} = (kstr){{{st}.p + {k}, 1}};")
        self.ind += 1
        self.gen_block_stmts(s.body, None)
        self.ind -= 1
        self.emit("}")
        self.ind -= 1
        self.emit("}")

    def gen_if(self, e: A.IfExpr, mode):
        c = self.gen_expr(e.cond)
        self.emit(f"if ({c}) {{")
        self.ind += 1
        self.gen_block_stmts(e.then_body, mode)
        self.ind -= 1
        eb = e.else_body
        while eb is not None:
            if isinstance(eb, A.IfExpr):
                pre, c2 = self.capture(lambda: self.gen_expr(eb.cond))
                if pre:
                    self.emit("} else {")
                    self.ind += 1
                    self.gen_if(eb, mode)
                    self.ind -= 1
                    break
                self.emit(f"}} else if ({c2}) {{")
                self.ind += 1
                self.gen_block_stmts(eb.then_body, mode)
                self.ind -= 1
                eb = eb.else_body
            else:
                self.emit("} else {")
                self.ind += 1
                self.gen_block_stmts(eb, mode)
                self.ind -= 1
                eb = None
        self.emit("}")

    def pattern_cond(self, p: A.Pattern, scrut: str, st) -> str | None:
        if p.kind in ("wildcard", "bind"):
            return None
        if p.kind == "int":
            return f"{scrut} == {c_int(p.value)}"
        if p.kind == "range":
            return f"({scrut} >= {c_int(p.value[0])} && {scrut} <= {c_int(p.value[1])})"
        if p.kind == "bool":
            return scrut if p.value else f"!{scrut}"
        if p.kind == "str":
            lit, n = c_string(p.value)
            return f"k_str_eq_lit({scrut}, {lit}, {n})"
        raise NotImplementedError(p.kind)

    def gen_match(self, e: A.MatchExpr, mode):
        sc = self.new_tmp("_m")
        self.emit(f"{self.ctype(e.scrut_ty)} {sc} = {self.gen_expr(e.scrutinee)};")
        depth = 0
        first = True
        for arm in e.arms:
            for p in arm.pattern:
                if p.kind == "bind":
                    p.sym.cname = sc
            conds = [self.pattern_cond(p, sc, e.scrut_ty) for p in arm.pattern]
            if any(c is None for c in conds):
                cond = None
            else:
                cond = " || ".join(conds) if len(conds) > 1 else conds[0]
                if len(conds) > 1:
                    cond = f"({cond})"
            if arm.guard is not None:
                pre, g = self.capture(lambda: self.gen_expr(arm.guard))
                if pre:
                    # guard needs statements: nest
                    if not first:
                        self.emit("} else {")
                        self.ind += 1
                        depth += 1
                    self.lines.extend(("    " * self.ind) + l.strip() for l in pre)
                    first = True
                g = f"({g})"
                cond = g if cond is None else f"{cond} && {g}"
            if cond is None:
                if first:
                    self.emit("{")
                else:
                    self.emit("} else {")
                self.ind += 1
                self.gen_arm_body(arm, mode)
                self.ind -= 1
                self.emit("}")
                first = None
                break
            if first:
                self.emit(f"if ({cond}) {{")
                first = False
            else:
                self.emit(f"}} else if ({cond}) {{")
            self.ind += 1
            self.gen_arm_body(arm, mode)
            self.ind -= 1
        if first is False:
            self.emit("}")
        for _ in range(depth):
            self.ind -= 1
            self.emit("}")

    def gen_arm_body(self, arm, mode):
        b = arm.body
        if isinstance(b, A.Block):
            self.gen_block_stmts(b, mode)
        elif mode is None:
            c = self.gen_expr(b)
            if c:
                self.emit(c + ";")
        else:
            self.gen_value_into(b, mode)

    # ── expressions ────────────────────────────────────────────────
    def gen_expr(self, e) -> str:
        m = getattr(self, "g_" + type(e).__name__)
        return m(e)

    def g_IntLit(self, e):
        if getattr(e, "as_float", False):
            return c_float(float(e.value))
        if getattr(e, "as_ptr", False):
            if e.value == 0:
                return "((void *)0)"
            return f"((void *)(uintptr_t){c_int(e.value)})"
        st = getattr(e, "sized_ty", None)
        if st is not None:
            return f"(({SIZED_C[st]}){c_int(e.value)})"
        return c_int(e.value)

    def g_NullLit(self, e):
        return "((void *)0)"

    def g_FloatLit(self, e):
        return c_float(e.value)

    def g_BoolLit(self, e):
        return "true" if e.value else "false"

    def g_StrLit(self, e):
        if e.parts is None:
            lit, n = c_string(e.value)
            return f"KS({lit}, {n})"
        items = [self.str_part(p) for p in e.parts]
        if len(items) == 1:
            return items[0]
        return f"k_concatn({len(items)}, (kstr[]){{{', '.join(items)}}})"

    def str_part(self, p) -> str:
        if isinstance(p, str):
            lit, n = c_string(p)
            return f"KS({lit}, {n})"
        ex, fs, _ = p
        c = self.gen_expr(ex)
        t = prune(ex.ty)
        if fs is None:
            return self.to_str(t, c)
        fill, align, zero, width, prec, typ = fs
        fl = c_string(fill)[0].strip('"')
        fl = "'\\''" if fill == "'" else f"'{fl}'"
        al = f"'{align}'" if align else "0"
        ty = f"'{typ}'" if typ else "0"
        args = f"{fl}, {al}, {int(zero)}, {width}, {prec}, {ty}"
        if t is INT:
            return f"k_fmt_int({c}, {args})"
        if t is FLOAT:
            return f"k_fmt_float({c}, {args})"
        return f"k_fmt_str({self.to_str(t, c)}, {args})"

    def g_Ident(self, e):
        return e.sym.cname

    def g_UnaryOp(self, e):
        c = self.gen_expr(e.operand)
        if e.op == "-":
            return f"(-{c})"
        return f"(!{c})"

    def g_BinaryOp(self, e):
        op = e.op
        if op in ("&&", "||"):
            lc = self.gen_expr(e.left)
            pre, rc = self.capture(lambda: self.gen_expr(e.right))
            if not pre:
                return f"({lc} {op} {rc})"
            t = self.new_tmp()
            self.emit(f"bool {t} = {lc};")
            self.emit(f"if ({'' if op == '&&' else '!'}{t}) {{")
            self.lines.extend("    " + l for l in pre)
            self.emit(f"    {t} = {rc};")
            self.emit("}")
            return t
        if op == "in":
            return self.gen_in(e)
        lc = self.gen_expr(e.left)
        rc = self.gen_expr(e.right)
        return self.binop(op, prune(e.left.ty), lc, rc, e.right)

    def binop(self, op, lt, lc, rc, right_node=None) -> str:
        if lt is STR:
            if op == "+":
                return f"k_concat({lc}, {rc})"
            if op == "==":
                return f"k_str_eq({lc}, {rc})"
            if op == "!=":
                return f"(!k_str_eq({lc}, {rc}))"
            return f"(k_str_cmp({lc}, {rc}) {op} 0)"
        if (lt is INT or lt in SIZED_INTS) and op in ("/", "%"):
            lit = isinstance(right_node, A.IntLit) and right_node.value not in (0, -1)
            if lit or lt in SIZED_INTS:
                return f"({lc} {op} {rc})"
            return f"k_{'div' if op == '/' else 'mod'}({lc}, {rc})"
        if lt is FLOAT and op == "%":
            return f"fmod({lc}, {rc})"
        if (lt is INT or lt in SIZED_INTS) and op == "<<":
            return f"(({self.ctype(lt)})((uint64_t)({lc}) << ({rc} & 63)))"
        if (lt is INT or lt in SIZED_INTS) and op == ">>":
            return f"({lc} >> ({rc} & 63))"
        return f"({lc} {op} {rc})"

    def gen_in(self, e):
        kind = e.in_kind
        if kind == "range":
            x = self.new_tmp()
            self.emit(f"int64_t {x} = {self.gen_expr(e.left)};")
            a = self.gen_expr(e.right.start)
            b = self.gen_expr(e.right.end)
            op = "<=" if e.right.inclusive else "<"
            return f"({x} >= {a} && {x} {op} {b})"
        if kind == "str":
            return f"k_str_contains({self.gen_expr(e.right)}, {self.gen_expr(e.left)})"
        arr_t = prune(e.right.ty)
        return f"{self.arrname(arr_t)}_contains({self.gen_expr(e.right)}, {self.gen_expr(e.left)})"

    def g_CastExpr(self, e):
        c = self.gen_expr(e.expr)
        src = prune(e.expr.ty)
        dst = prune(e.ty)
        if dst is STR:
            return self.to_str(src, c)
        if dst is CSTR:
            if src is STR:
                return f"k_cstr({c})"
            return c
        if src is dst:
            return c
        if dst is PTR:
            return f"((void *)(uintptr_t)({c}))"
        if src is PTR:
            return f"(({self.ctype(dst)})(uintptr_t)({c}))"
        return f"(({self.ctype(dst)})({c}))"

    def g_ArrayLit(self, e):
        n = self.arrname(e.ty)
        if not e.elems:
            return f"{n}_new(0)"
        items = [self.gen_expr(x) for x in e.elems]
        return f"{n}_from({len(items)}, ({self.ctype(prune(e.ty).elem)}[]){{{', '.join(items)}}})"

    def g_StructLit(self, e):
        st = e.sty
        inits = [f".{fname} = {self.gen_expr(v)}" for (fname, _), v in zip(st.fields, e.ordered)]
        if not inits:
            return f"(S_{st.name}){{0}}"
        return f"(S_{st.name}){{{', '.join(inits)}}}"

    def g_Index(self, e):
        obj = self.gen_expr(e.obj)
        if e.kind in ("arr_slice", "str_slice"):
            a = self.gen_expr(e.index.start)
            b = self.gen_expr(e.index.end)
            if e.inclusive:
                b = f"({b}) + 1"
            if e.kind == "str_slice":
                return f"k_str_slice({obj}, {a}, {b})"
            return f"{self.arrname(e.ty)}_slice({obj}, {a}, {b})"
        idx = self.gen_expr(e.index)
        if e.kind == "str":
            return f"k_str_at({obj}, {idx})"
        return f"(*{self.arrname(e.obj.ty)}_at({obj}, {idx}))"

    def g_FieldAccess(self, e):
        if e.kind == "call":
            return self.gen_expr(e.as_call)
        if e.kind == "arr_ptr":
            return f"((void *)({self.gen_expr(e.obj)})->data)"
        if e.kind == "module_global":
            return e.sym.cname
        return f"{self.gen_expr(e.obj)}.{e.field}"

    def g_Assign(self, e):
        tgt = e.target
        val = e.value
        if getattr(val, "compound", False) and not isinstance(tgt, A.Ident):
            p = self.new_tmp("_p")
            lv = self.gen_expr(tgt)
            self.emit(f"{self.ctype(tgt.ty)} *{p} = &{lv};")
            rc = self.gen_expr(val.right)
            return f"*{p} = {self.binop(val.op, prune(tgt.ty), '*' + p, rc, val.right)}"
        lv = self.gen_expr(tgt)
        if isinstance(val, (A.IfExpr, A.MatchExpr, A.Block)) and prune(val.ty) not in (UNIT, NEVER):
            t = self.new_tmp()
            self.emit(f"{self.ctype(val.ty)} {t};")
            self.gen_value_into(val, ("assign", t))
            return f"{lv} = {t}"
        return f"{lv} = {self.gen_expr(val)}"

    def g_Block(self, e):
        t = prune(e.ty)
        if e.used and t not in (UNIT, NEVER):
            tmp = self.new_tmp()
            self.emit(f"{self.ctype(t)} {tmp};")
            self.gen_value_into(e, ("assign", tmp))
            return tmp
        self.emit("{")
        self.ind += 1
        self.gen_block_stmts(e, None)
        self.ind -= 1
        self.emit("}")
        return ""

    def g_IfExpr(self, e):
        t = prune(e.ty)
        if e.used and t not in (UNIT, NEVER):
            # simple ternary when both branches are single pure expressions
            tern = self.try_ternary(e)
            if tern:
                return tern
            tmp = self.new_tmp()
            self.emit(f"{self.ctype(t)} {tmp};")
            self.gen_if(e, ("assign", tmp))
            return tmp
        self.gen_if(e, None)
        return ""

    def try_ternary(self, e):
        def single(b):
            if isinstance(b, A.Block) and len(b.stmts) == 1 and isinstance(b.stmts[0], A.ExprStmt):
                x = b.stmts[0].expr
                if isinstance(x, (A.IntLit, A.FloatLit, A.BoolLit, A.StrLit, A.Ident, A.BinaryOp, A.Call, A.FieldAccess, A.Index)):
                    return x
            return None
        a = single(e.then_body)
        b = single(e.else_body) if isinstance(e.else_body, A.Block) else None
        if a is None or b is None:
            return None
        if prune(a.ty) is NEVER or prune(b.ty) is NEVER:
            return None
        pc, c = self.capture(lambda: self.gen_expr(e.cond))
        pa, ca = self.capture(lambda: self.gen_expr(a))
        pb, cb = self.capture(lambda: self.gen_expr(b))
        if pc or pa or pb:
            return None
        return f"({c} ? {ca} : {cb})"

    def g_MatchExpr(self, e):
        t = prune(e.ty)
        if e.used and t not in (UNIT, NEVER):
            tmp = self.new_tmp()
            self.emit(f"{self.ctype(t)} {tmp};")
            self.gen_match(e, ("assign", tmp))
            return tmp
        self.gen_match(e, None)
        return ""

    def g_Call(self, e):
        kind, tgt = e.target
        if kind == "user":
            args = []
            for a in e.cargs:
                c = self.gen_expr(a)
                if getattr(a, "coerce_to_cstr", False):
                    c = f"k_cstr({c})"
                args.append(c)
            return f"{tgt.cname}({', '.join(args)})"
        return self.gen_builtin(tgt, e)

    def print_value(self, f, t, c):
        t = prune(t)
        if t is STR:
            self.emit(f"k_print_str({f}, {c});")
        elif t is INT or t in SIZED_INTS:
            self.emit(f"k_print_int({f}, (int64_t)({c}));")
        elif t is FLOAT:
            self.emit(f"k_print_float({f}, {c});")
        elif t is BOOL:
            self.emit(f"k_print_bool({f}, {c});")
        else:
            self.emit(f"k_print_str({f}, {self.to_str(t, c)});")

    def gen_print(self, f, a):
        if isinstance(a, A.StrLit):
            if a.parts is None:
                lit, n = c_string(a.value)
                if n:
                    self.emit(f"k_print_lit({f}, {lit}, {n});")
                return
            for p in a.parts:
                if isinstance(p, str):
                    lit, n = c_string(p)
                    self.emit(f"k_print_lit({f}, {lit}, {n});")
                elif p[1] is None:
                    self.print_value(f, p[0].ty, self.gen_expr(p[0]))
                else:
                    self.emit(f"k_print_str({f}, {self.str_part(p)});")
            return
        self.print_value(f, a.ty, self.gen_expr(a))

    def gen_builtin(self, name, e) -> str:
        a = e.cargs
        g = self.gen_expr
        if name in ("print", "println", "eprint", "eprintln"):
            f = "stderr" if name.startswith("e") else "stdout"
            for i, x in enumerate(a):
                if i:
                    self.emit(f"k_print_lit({f}, \" \", 1);")
                self.gen_print(f, x)
            if name.endswith("ln"):
                self.emit(f"k_print_lit({f}, \"\\n\", 1);")
            return ""
        if name in ("str", "to_str"):
            return self.to_str(a[0].ty, g(a[0]))
        if name == "len":
            t = prune(a[0].ty)
            return f"({g(a[0])}).n" if t is STR else f"({g(a[0])})->len"
        if name == "fill":
            return f"{self.arrname(e.ty)}_fill({g(a[0])}, {g(a[1])})"
        if name == "contains":
            if e.variant == "str":
                return f"k_str_contains({g(a[0])}, {g(a[1])})"
            return f"{self.arrname(a[0].ty)}_contains({g(a[0])}, {g(a[1])})"
        if name in ("push", "pop", "clear", "reverse"):
            n = self.arrname(a[0].ty)
            args = ", ".join(g(x) for x in a)
            return f"{n}_{name}({args})"
        if name == "sort":
            return f"{self.arrname(a[0].ty)}_sorted({g(a[0])})"
        if name == "sum":
            return f"{self.arrname(a[0].ty)}_sum({g(a[0])})"
        if name == "join":
            sep = g(a[1]) if len(a) > 1 else 'KS("", 0)'
            return f"k_str_join({g(a[0])}, {sep})"
        simple = {
            "split": "k_str_split", "split_whitespace": "k_str_split_ws", "lines": "k_str_lines",
            "trim": "k_str_trim", "starts_with": "k_str_starts_with", "ends_with": "k_str_ends_with",
            "replace": "k_str_replace", "repeat": "k_str_repeat", "find": "k_str_find",
            "parse_int": "k_parse_int", "parse_float": "k_parse_float", "sqrt": "sqrt", "floor": "floor",
            "ceil": "ceil", "sin": "sin", "cos": "cos", "pow": "pow", "exit": "k_exit", "panic": "k_panic",
            "read_line": "k_read_line", "now_ms": "k_now_ms", "env": "k_env",
            "fs.read_text": "k_read_text", "fs.write_text": "k_write_text", "fs.exists": "k_exists",
        }
        if name in simple:
            return f"{simple[name]}({', '.join(g(x) for x in a)})"
        if name == "to_upper":
            return f"k_str_case({g(a[0])}, 1)"
        if name == "to_lower":
            return f"k_str_case({g(a[0])}, 0)"
        if name == "ask":
            return f"k_ask({g(a[0]) if a else 'KS(\"\", 0)'})"
        if name == "abs":
            t = prune(a[0].ty)
            return f"k_abs_i({g(a[0])})" if t is INT else f"fabs({g(a[0])})"
        if name in ("min", "max"):
            t = prune(a[0].ty)
            suf = {INT: "i", FLOAT: "f", STR: "s"}[t]
            return f"k_{name}_{suf}({g(a[0])}, {g(a[1])})"
        if name == "assert":
            m = g(a[1]) if len(a) > 1 else 'KS("assert", 6)'
            return f"k_assert({g(a[0])}, {m}, {self.loc_str(e)})"
        raise NotImplementedError(name)


def generate_c(prog: A.Program, checker: Checker, filename: str, test_mode: bool = False) -> str:
    return CGen(checker, filename).gen_program(prog, test_mode=test_mode)
